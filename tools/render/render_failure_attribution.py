"""Render paper figures from the shared failure report, without reclassifying runs."""

from __future__ import annotations

import argparse
from collections import Counter
from collections.abc import Mapping
from pathlib import Path
from typing import Any

from egocua.workspace import read_json_strict


MAIN_MODELS = (
    ("gpt-6.1-terra", "Terra"),
    ("gemini-3.8-flash", "Gemini"),
    ("doubao-seed-2-1-pro-260915", "Doubao"),
    ("deepseek-flash", "DeepSeek"),
    ("kimi-k2.6", "Kimi"),
    ("qwen3.5-27b", "Qwen"),
)
SETTINGS = (
    ("computer_use", "Computer-Use"),
    ("offline_ego_use", "Offline"),
    ("online", "Online"),
)
CATEGORIES = ("P", "U", "L", "S", "E", "unknown", "pending")
UNATTRIBUTED = ("unknown", "pending")

# Hues stay clear of the model and combination colors used by the other result figures.
SEGMENTS = {
    "P": ("Perception", "5E4A8C", "white"),
    "L": ("Linking", "A99ACB", "black!80"),
    "U": ("Intent", "A63D57", "white"),
    "S": ("State Control", "6E7A2E", "white"),
    "E": ("Verification", "C0C487", "black!80"),
    "unattributed": ("Unattributed", "D5D8DC", "black!70"),
}

CHALLENGE_GROUPS = (
    ("Context Grounding", ("P", "L")),
    ("Intent Continuity", ("U",)),
    ("Execution Adaptation", ("S", "E")),
)
PLOT_ORDER = (*(key for _, keys in CHALLENGE_GROUPS for key in keys), "unattributed")


def display_counts(summary: Mapping[str, Any]) -> tuple[list[int], int, int]:
    """Keep the report's stage, uncertainty, processing, and validity boundaries."""
    counts = [summary["stages"][stage]["count"] for stage in "PULSE"]
    counts += [summary["unknown_failures"], summary["pending_attributions"]]
    eligible = summary["valid_model_failures"]
    review = summary["unresolved_run_validity"]
    if any(not isinstance(value, int) or value < 0 for value in [*counts, eligible, review]):
        raise ValueError("failure counts must be nonnegative integers")
    if sum(counts) != eligible:
        raise ValueError("failure categories do not sum to the eligible denominator")
    return counts, eligible, review


PLOT_WIDTH = 4.00
PANEL_SPACING = 5.45


def comparison_models(report: Mapping[str, Any]) -> tuple[tuple[str, str], ...]:
    """Use the same evaluated main models in every setting panel."""
    groups = report["statistics"]["matrices"]["model_setting"]
    models = tuple(
        (model, label)
        for model, label in MAIN_MODELS
        if all(f"{model} / {setting}" in groups for setting, _ in SETTINGS)
    )
    if not models:
        raise ValueError("no main models have all three settings")
    return models


def figure_counts(summary: Mapping[str, Any]) -> tuple[dict[str, int], int]:
    """Pool unknown and missing Judge outputs for display."""
    counts, eligible, _ = display_counts(summary)
    by_category = dict(zip(CATEGORIES, counts, strict=True))
    by_category["unattributed"] = sum(by_category.pop(key) for key in UNATTRIBUTED)
    return by_category, eligible


def _bar_lines(summary: Mapping[str, Any], y: float) -> list[str]:
    by_category, eligible = figure_counts(summary)
    if not eligible:
        raise ValueError("no eligible failures in a comparison cell")
    lines = []
    start = 0.0
    for key in PLOT_ORDER:
        count = by_category[key]
        end = start + count / eligible * PLOT_WIDTH
        if count:
            lines.append(rf"\filldraw[fill=failure{key},draw=white,line width=.5pt] ({start:.5f},{y - .14:.3f}) rectangle ({end:.5f},{y + .14:.3f});")
            if count / eligible >= .10:
                text_color = SEGMENTS[key][2]
                lines.append(rf"\node[text={text_color},inner sep=0pt] at ({(start + end) / 2:.5f},{y:.3f}) {{{100 * count / eligible:.0f}}};")
        start = end
    return lines


def render_setting_figure(report: Mapping[str, Any]) -> str:
    groups = report["statistics"]["matrices"]["model_setting"]
    models = comparison_models(report)
    has_unattributed = any(
        figure_counts(groups[f"{model} / {setting}"])[0]["unattributed"]
        for model, _ in models for setting, _ in SETTINGS
    )
    bottom = -.42 * (len(models) - 1) - .18
    lines = [
        "% Generated by tools.render.render_failure_attribution from the shared report.",
        r"\begin{tikzpicture}[x=1cm,y=1cm,font=\footnotesize]",
    ]
    for key, (_, color, _) in SEGMENTS.items():
        lines.append(rf"\definecolor{{failure{key}}}{{HTML}}{{{color}}}")
    if not has_unattributed:
        lines.append(r"\begin{scope}[xshift=1.90cm]")
    headings = tuple(label for label, _ in CHALLENGE_GROUPS)
    group_positions = ((1.25, 4.45), (5.15, 7.45), (8.15, 11.95))
    if has_unattributed:
        headings += ("Attribution status",)
        group_positions += ((12.65, 15.05),)
    for label, (start, end) in zip(headings, group_positions, strict=True):
        lines += [
            rf"\node[anchor=south,font=\footnotesize\bfseries,text=black!70] at ({(start + end) / 2:.2f},1.62) {{{label}}};",
            rf"\draw[black!30,line width=.4pt] ({start:.2f},1.57) -- ({end:.2f},1.57);",
        ]
    legend_positions = (1.35, 3.25, 5.40, 8.25, 10.35)
    legend_order = PLOT_ORDER[:-1]
    if has_unattributed:
        legend_order += ("unattributed",)
        legend_positions += (13.00,)
    for key, x in zip(legend_order, legend_positions, strict=True):
        lines += [
            rf"\filldraw[fill=failure{key},draw=black!20,line width=.3pt] ({x:.2f},1.17) rectangle ++(.25,.16);",
            rf"\node[anchor=west,inner sep=2pt,text height=1.5ex,text depth=.3ex] at ({x + .3:.2f},1.25) {{{SEGMENTS[key][0]}}};",
        ]
    if not has_unattributed:
        lines.append(r"\end{scope}")
    for panel_index, (setting, label) in enumerate(SETTINGS):
        title = label if setting == "computer_use" else f"{label} Ego Use"
        lines += [
            rf"\begin{{scope}}[xshift={1.05 + panel_index * PANEL_SPACING:.2f}cm]",
            rf"\node[font=\footnotesize\bfseries] at ({PLOT_WIDTH / 2:.2f},.73) {{({chr(97 + panel_index)}) {title}}};",
        ]
        for tick in (0, 50, 100):
            x = tick / 100 * PLOT_WIDTH
            lines += [
                rf"\draw[black!12,line width=.3pt] ({x:.3f},.18) -- ({x:.3f},{bottom:.3f});",
                rf"\node[anchor=north,text=black!60] at ({x:.3f},{bottom - .10:.3f}) {{{tick}\%}};",
            ]
        for row_index, (model, name) in enumerate(models):
            y = -row_index * .42
            if panel_index == 0:
                lines.append(rf"\node[anchor=east] at (-.12,{y:.3f}) {{{name}}};")
            lines.extend(_bar_lines(groups[f"{model} / {setting}"], y))
        lines.append(r"\end{scope}")
    lines.append(r"\end{tikzpicture}")
    return "\n".join(lines) + "\n"


def render_counts_table(report: Mapping[str, Any]) -> str:
    groups = report["statistics"]["matrices"]["model_setting"]
    human_labels = Counter(
        (row["model"], row["setting"])
        for row in report["attributions"]
        if row["attribution_method"] == "human_adjudication"
    )
    total_counts, _, _ = display_counts(report["statistics"]["summary"])
    error_columns = slice(len("PULSE"))
    lines = [
        "% Generated by tools.render.render_failure_attribution from the shared report.",
        r"\begin{table*}",
        r"\centering\small",
        r"\caption{Labeled failures by model and setting. Human-labeled counts are included in the five error columns.}",
        r"\label{tab:failure-counts}",
        r"\renewcommand{\arraystretch}{1.12}",
        r"\setlength{\tabcolsep}{3pt}",
        r"\begin{tabular*}{\textwidth}{@{\extracolsep{\fill}}llrrrrrr@{}}",
        r"\toprule",
        r" & & \multicolumn{5}{c}{Assigned error} & \\",
        r"\cmidrule(lr){3-7}",
        r"Model & Setting & Perception & Intent & Linking & State Control & Verification & Human-labeled\\",
        r"\midrule",
    ]
    models = (*MAIN_MODELS, ("ui-tars-7b", "UI-TARS"))
    for model_index, (model, name) in enumerate(models):
        if model_index:
            lines.append(r"\addlinespace")
        for setting, label in SETTINGS:
            key = f"{model} / {setting}"
            if key not in groups:
                continue
            counts, _, _ = display_counts(groups[key])
            values = [name, label, *map(str, (*counts[error_columns], human_labels[model, setting]))]
            lines.append(" & ".join(values) + r"\\")
    total = ["Total", "All available", *map(
        str, (*total_counts[error_columns], sum(human_labels.values()))
    )]
    lines += [r"\midrule", " & ".join(total) + r"\\"]
    lines += [r"\bottomrule", r"\end{tabular*}", r"\end{table*}"]
    return "\n".join(lines) + "\n"


def _require_current_studies(root: Path, report: Mapping[str, Any]) -> None:
    studies = read_json_strict(root / "configs/failure-judge.json")["studies"]
    registered = {str((root / path).resolve()) for path in studies}
    reported = {
        str((root / path).resolve())
        for sources in report["source_studies"].values()
        for path in sources
    }
    if registered != reported:
        raise ValueError("failure report does not use the current registered studies")


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path("."))
    args = parser.parse_args(argv)
    root = args.root.resolve()
    report = read_json_strict(root / "artifacts/reports/failure-attribution-formal.json")
    _require_current_studies(root, report)
    figure = render_setting_figure(report)
    counts = render_counts_table(report)
    directory = root / "paper/figures"
    directory.mkdir(parents=True, exist_ok=True)
    (directory / "failure_attribution.tex").write_text(figure)
    (directory / "failure_attribution_counts.tex").write_text(counts)


if __name__ == "__main__":
    main()
